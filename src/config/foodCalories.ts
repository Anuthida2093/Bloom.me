/** คำค้นแบบไม่สนช่องว่าง/ตัวพิมพ์ — ค้นทั้งชื่อเมนูและชื่อเรียกอื่น (aliases) */
export function matchesFood(item: FoodItem, rawQuery: string): boolean {
  const norm = (t: string) => t.toLowerCase().replace(/\s+/g, '')
  const q = norm(rawQuery)
  if (!q) return true
  return norm(item.name).includes(q) || (item.aliases ?? []).some((a) => norm(a).includes(q))
}
