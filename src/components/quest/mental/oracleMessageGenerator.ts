const MOODS: Mood[] = ['HAPPY', 'ENERGETIC', 'FOCUSED', 'CALM', 'SAD', 'ANXIOUS', 'TIRED', 'ANGRY']

/** จำนวนชุดค่าผสมอิสระ "ต่ออารมณ์เดียว" — คำนวณจากคลังจริง ไม่ใช่เลขตายตัว (>1,000 ทุกอารมณ์) */
export const COMBINATIONS_PER_MOOD: Record<Mood, number> = Object.fromEntries(
  MOODS.map((m) => [m, PREFIXES[m].length * CORE_LINES[m].length * SUFFIXES[m].length]),
) as Record<Mood, number>

export const TOTAL_COMBINATIONS = MOODS.reduce((sum, m) => sum + COMBINATIONS_PER_MOOD[m], 0)

function pick<T>(pool: T[], rng: () => number): T {
  return pool[Math.floor(rng() * pool.length)]
}

/**
 * generateOracleMessage — ผสม prefix/core/suffix ตามอารมณ์ผู้ใช้ + คำใบ้จากไพ่ที่จับได้
 * seedKey เดิม (เช่น `${moodEntry.id}-${card.id}`) จะได้ข้อความเดิมเป๊ะเสมอ (deterministic)
 * เปลี่ยน seedKey (วันใหม่/ไพ่ใหม่) จะได้ข้อความชุดใหม่ที่ต่างออกไปตามอารมณ์นั้นจริงๆ
 */
export function generateOracleMessage(card: OracleCard, mood: Mood, seedKey: string): string {
  const rng = seededRandom(seedKey)
  const prefix = pick(PREFIXES[mood], rng)
  const core = pick(CORE_LINES[mood], rng)
  const suffix = pick(SUFFIXES[mood], rng)
  return `${prefix} "${card.title}" — ${core} ${suffix}`
}
