export type FoodCategory =
  | 'rice' | 'noodle' | 'curry' | 'side' | 'isan' | 'chili'
  | 'breakfast' | 'fastfood' | 'drink' | 'fruit' | 'dessert' | 'snack'

export interface FoodItem {
  name: string
  /** แคลอรี่โดยประมาณต่อ 1 หน่วย */
  kcal: number
  /** หน่วยที่ใช้นับ เช่น จาน/ชาม/ชิ้น/แก้ว */
  unit: string
  category: FoodCategory
  /** ชื่อเรียกอื่นที่ใช้ค้นหา */
  aliases?: string[]
}

